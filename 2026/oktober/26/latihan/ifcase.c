#include <stdio.h>
int main() {
    //Declaration
    int nilai;

    //Algorithm
    scanf("%d", &nilai);

    if (nilai >= 60)
        printf("Lulus\n");
    else
        printf("Tidak Lulus\n");

    switch (nilai) {
        case 100: printf("Nilai Sempurna"); break;
        case 80: printf("Nilai Bagus"); break;
        default: printf("Tetap Semangat");
    }
    return 0;
}

