#include <stdio.h>

int main(void) {
    //Declaration
    int tahun;

    //Algorithm
    printf("Masukkan tahun: ");
    scanf("%d", &tahun);

    if (tahun % 400 == 0 || (tahun % 4 == 0 && tahun % 100 != 0))
        printf("Tahun kabisat");
    else
        printf("Bukan tahun kabisat");

    return 0;
}


